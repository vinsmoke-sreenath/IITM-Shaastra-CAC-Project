/*
 * Returns true (and restarts the period) when period_ms has passed since
 * *last_ms. Unsigned subtraction keeps this correct when HAL_GetTick() wraps.
 */
static bool Period_Elapsed(uint32_t now, uint32_t *last_ms, uint32_t period_ms)
{
    if ((uint32_t)(now - *last_ms) >= period_ms)
    {
        *last_ms = now;
        return true;
    }
    return false;
}

