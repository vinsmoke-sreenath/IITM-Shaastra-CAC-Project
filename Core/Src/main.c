/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_TIM2_Init();
  MX_TIM4_Init();
  MX_UART5_Init();
  MX_TIM1_Init();
  MX_TIM3_Init();
  MX_TIM5_Init();
  MX_TIM8_Init();
  MX_TIM12_Init();
  /* USER CODE BEGIN 2 */

  Encoder_Init(&htim2, &htim4);
  Motor_Init(&htim1, &htim5, &htim8);
  Servo_Init(&htim3, &htim12);
  PID_Init();

  if (UART_Comm_Init(&huart5) != HAL_OK)
  {
      Motor_Set_Speeds(0, 0);
      Error_Handler();
  }


  imu_init_status = mpu6050_init();

  imu_fail_count = 0;

  if (imu_init_status == HAL_OK)
  {
      imu_who_status = mpu6050_who_am_i((uint8_t *)&imu_who_am_i);

      if ((imu_who_status == HAL_OK) &&
          (imu_who_am_i == 0x68))
      {
          imu_ok = true;
      }
      else
      {
          imu_ok = false;
      }
  }
  else
  {
      imu_ok = false;
  }

  last_led_toggle     = HAL_GetTick();
  last_encoder_update = HAL_GetTick();
  last_pid_update     = HAL_GetTick();
  last_imu_send       = HAL_GetTick();
  last_imu_sample     = HAL_GetTick();
  last_imu_retry      = HAL_GetTick();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
      uint32_t now = HAL_GetTick();

      /* PE3 heartbeat*/
      if (Period_Elapsed(now, &last_led_toggle, LED_TOGGLE_PERIOD_MS))
      {
          HAL_GPIO_TogglePin(LED_PORT, LED_PIN);
      }

      /* Encoder RPM + telemetry to the Raspberry Pi */
      if (Period_Elapsed(now, &last_encoder_update, ENCODER_SAMPLE_TIME_MS))
      {
          Encoder_Update();
          UART_Comm_Send_RPM(Encoder_Get_Left_RPM(), Encoder_Get_Right_RPM());
      }

      /* IMU telemetry to the Raspberry Pi (only while the IMU is healthy) */
      if (Period_Elapsed(now, &last_imu_send, IMU_SEND_PERIOD_MS) && imu_ok)
      {
          UART_Comm_Send_IMU(imu_latest.x_acc,  imu_latest.y_acc,  imu_latest.z_acc,
                             imu_latest.x_gyro, imu_latest.y_gyro, imu_latest.z_gyro);
      }

      /* Stop the rover if the Pi stopped sending VEL keep-alives */
      UART_Comm_Check_Timeout();

      /* Closed-loop motor control (must run after Encoder_Update) */
      if (Period_Elapsed(now, &last_pid_update, PID_SAMPLE_TIME_MS))
      {
          PID_Update();
      }

      /* MPU6050: sampled on every pass of the loop while healthy */
      if (Period_Elapsed(now, &last_imu_sample, IMU_SAMPLE_PERIOD_MS))
      {
          IMU_Poll(now);
      }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

